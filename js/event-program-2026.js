function activityHasDay(activity, day) {
  if (day === "25") return Boolean(localise(activity.sessions25).trim());
  if (day === "26") return Boolean(localise(activity.sessions26).trim());
  return true;
}

function activitySortWeight(activity) {
  if (activity.zone === "entrance") return -100;
  if (activity.zone === "eu") return 900;
  if (activity.zone === "debrief") return 910;
  if (activity.id === "AVE-004") return -100;
  if (activity.id === "AVE-006") return 900;
  if (activity.id === "AVE-005") return 910;
  return Number.parseInt(String(activity.id || "").replace(/\D/g, ""), 10) || 0;
}

const programZoneOrder = ["entrance", "investigation", "eu", "debrief"];

function activityZoneKey(activity) {
  if (activity.zone) return activity.zone;
  if (activity.id === "AVE-004") return "entrance";
  if (activity.id === "AVE-005") return "debrief";
  if (activity.id === "AVE-006") return "eu";
  return "investigation";
}

function createDetail(label, value) {
  const text = localise(value).trim();
  if (!text) return "";
  return `<div><dt>${label}</dt><dd>${text}</dd></div>`;
}

function activityImageMarkup(activity) {
  const image = localise(activity.image).trim();
  const title = localise(activity.title).trim();
  const fallbackImage = eventProgramme?.image ? `events-ern-2026_img/${eventProgramme.image}` : "";
  const selectedImage = image || fallbackImage;
  if (!selectedImage) {
    return `<div class="program-activity-image-placeholder">${copy.imagePlaceholder}</div>`;
  }
  const src = selectedImage.startsWith("http") || selectedImage.startsWith(assetPrefix) ? selectedImage : `${assetPrefix}${selectedImage}`;
  return `<img src="${src}" alt="${title}">`;
}

function renderActivityCard(activity, currentDay = "all") {
  const title = localise(activity.title).trim();
  const type = localise(activity.type).trim();
  const topic = localise(activity.topic).trim();
  const format = localise(activity.format).trim();
  const duration = localise(activity.duration).trim();
  const isEscapeRoom = type.toLowerCase().includes("escape room");
  const sessions25 = localise(activity.sessions25).trim();
  const sessions26 = localise(activity.sessions26).trim();
  const sessions = isEscapeRoom
    ? (currentDay === "25"
        ? (sessions25 ? `${copy.day25}: ${sessions25}` : "")
        : currentDay === "26"
          ? (sessions26 ? `${copy.day26}: ${sessions26}` : "")
          : [
              sessions25 ? `${copy.day25}: ${sessions25}` : "",
              sessions26 ? `${copy.day26}: ${sessions26}` : ""
            ].filter(Boolean).join(" · "))
    : "";
  const details = [
    createDetail(copy.labels.area, activity.area),
    createDetail(copy.labels.topic, activity.topic),
    createDetail(copy.labels.age, activity.age),
    isEscapeRoom ? createDetail(copy.labels.ageAdaptation, activity.ageAdaptation) : "",
    isEscapeRoom ? createDetail(copy.labels.format, activity.format) : "",
    createDetail(copy.labels.duration, duration ? (/^\d+$/.test(duration) ? `${duration} min` : duration) : ""),
    isEscapeRoom ? createDetail(copy.labels.sessions, sessions) : "",
    createDetail(copy.labels.maxParticipants, activity.maxParticipants),
    isEscapeRoom ? createDetail(copy.labels.booking, [localise(activity.bookingRequired), localise(activity.bookingMethod)].filter(Boolean).join(" · ")) : "",
    createDetail(copy.labels.accessibility, activity.accessibility),
    createDetail(copy.labels.partner, activity.partner)
  ].filter(Boolean).join("");

  return `
    <article class="program-activity-card" data-activity-id="${activity.id || ""}" data-zone="${activityZoneKey(activity)}" data-days="${activityHasDay(activity, "25") ? "25 " : ""}${activityHasDay(activity, "26") ? "26" : ""}">
      <div class="program-activity-media">${activityImageMarkup(activity)}</div>
      <div class="program-activity-body">
        <div class="program-activity-tags">
          ${type ? `<span class="program-activity-tag">${type}</span>` : ""}
          ${topic ? `<span class="program-activity-tag">${topic}</span>` : ""}
          ${isEscapeRoom && format ? `<span class="program-activity-tag">${format}</span>` : ""}
        </div>
        <h3>${title || localise(activity.id)}</h3>
        ${localise(activity.description).trim() ? `<p class="program-activity-description">${localise(activity.description).trim()}</p>` : ""}
        <dl class="program-activity-details">${details}</dl>
        ${localise(activity.bookingUrl).trim() ? `<a class="button button-primary program-activity-booking" href="${localise(activity.bookingUrl).trim()}" target="_blank" rel="noopener noreferrer">${localise(activity.bookingLabel).trim() || localise(activity.bookingMethod).trim() || copy.labels.booking}</a>` : ""}
      </div>
    </article>`;
}

function renderActivityZone(zoneKey, activities, currentDay) {
  const zone = copy.zones?.[zoneKey];
  const showInvestigationPlaceholder = zoneKey === "investigation" && eventKey !== "avezzano";
  if (!zone || (!activities.length && !showInvestigationPlaceholder)) return "";
  const showZoneDescription = zoneKey === "investigation";
  const countLabel = activities.length === 1 ? copy.zoneActivitySingular : copy.zoneActivityPlural;
  const countMarkup = zoneKey === "investigation" && activities.length
    ? `<p class="program-zone-count">${activities.length} ${countLabel}</p>`
    : "";
  const zoneBody = showInvestigationPlaceholder
    ? `${activities.length
        ? `<div class="program-zone-grid">
          ${activities.map((activity) => renderActivityCard(activity, currentDay)).join("")}
        </div>`
        : ""}
      <div class="program-zone-wip">
        <h4>${copy.investigationWipTitle}</h4>
        <p>${copy.investigationWipCopy}</p>
      </div>`
    : `<div class="program-zone-grid">
        ${activities.map((activity) => renderActivityCard(activity, currentDay)).join("")}
      </div>`;
  return `
    <section class="program-zone program-zone-${zoneKey}" aria-labelledby="program-zone-${zoneKey}-title">
      <div class="program-zone-heading">
        <div>
          ${countMarkup}
          <h3 id="program-zone-${zoneKey}-title">${zone.title}</h3>
        </div>
      </div>
      ${showZoneDescription ? `<p class="program-zone-description">${zone.description}</p>` : ""}
      ${zoneBody}
    </section>`;
}


const params = new URLSearchParams(window.location.search);
const eventKey = params.get("evento");
const pathLang = window.location.pathname.includes("/it/")
  ? "it"
  : window.location.pathname.includes("/fr/")
    ? "fr"
    : "en";
const htmlLang = document.documentElement.lang;
const lang = Object.prototype.hasOwnProperty.call(programI18n, htmlLang) ? htmlLang : pathLang;
const copy = programI18n[lang];
const eventProgramme = eventProgrammes2026[eventKey];
const assetPrefix = pathLang === "it" || pathLang === "fr" ? "../" : "";

function localise(value) {
  if (!value || typeof value === "string") return value || "";
  return value[lang] || value.en || value.it || value.fr || "";
}

function setText(id, text) {
  const element = document.getElementById(id);
  if (element) element.textContent = text;
}

function localisedPath(targetLang) {
  if (targetLang === "en") return `${assetPrefix}programmi-ern-2026.html`;
  return `${assetPrefix}${targetLang}/programmi-ern-2026.html`;
}

document.querySelectorAll("[data-program-lang-link]").forEach((link) => {
  const targetLang = link.dataset.programLangLink;
  const nextParams = new URLSearchParams(window.location.search);
  link.href = `${localisedPath(targetLang)}?${nextParams.toString()}`;
});


function normaliseDayFilter(day) {
  return day === "26" ? "26" : day === "25" ? "25" : "all";
}

function activityHasDay(activity, day) {
  if (day === "25") return Boolean(localise(activity.sessions25).trim());
  if (day === "26") return Boolean(localise(activity.sessions26).trim());
  return true;
}

function createDetail(label, value) {
  const text = localise(value).trim();
  if (!text) return "";
  return `<div><dt>${label}</dt><dd>${text}</dd></div>`;
}

function activityImageMarkup(activity) {
  const image = localise(activity.image).trim();
  const title = localise(activity.title).trim();
  if (!image) {
    return `<div class="program-activity-image-placeholder">${copy.imagePlaceholder}</div>`;
  }
  const src = image.startsWith("http") || image.startsWith(assetPrefix) ? image : `${assetPrefix}${image}`;
  return `<img src="${src}" alt="${title}">`;
}

function renderActivityCard(activity) {
  const title = localise(activity.title).trim();
  const type = localise(activity.type).trim();
  const topic = localise(activity.topic).trim();
  const format = localise(activity.format).trim();
  const duration = localise(activity.duration).trim();
  const sessions = [localise(activity.sessions25).trim(), localise(activity.sessions26).trim()].filter(Boolean).join(" · ");
  const details = [
    createDetail(copy.labels.area, activity.area),
    createDetail(copy.labels.topic, activity.topic),
    createDetail(copy.labels.age, activity.age),
    createDetail(copy.labels.ageAdaptation, activity.ageAdaptation),
    createDetail(copy.labels.format, activity.format),
    createDetail(copy.labels.duration, duration ? `${duration} min` : ""),
    createDetail(copy.labels.sessions, sessions),
    createDetail(copy.labels.maxParticipants, activity.maxParticipants),
    createDetail(copy.labels.booking, [localise(activity.bookingRequired), localise(activity.bookingMethod)].filter(Boolean).join(" · ")),
    createDetail(copy.labels.accessibility, activity.accessibility)
  ].filter(Boolean).join("");

  return `
    <article class="program-activity-card" data-days="${activityHasDay(activity, "25") ? "25 " : ""}${activityHasDay(activity, "26") ? "26" : ""}">
      <div class="program-activity-media">${activityImageMarkup(activity)}</div>
      <div class="program-activity-body">
        <div class="program-activity-tags">
          ${type ? `<span class="program-activity-tag">${type}</span>` : ""}
          ${topic ? `<span class="program-activity-tag">${topic}</span>` : ""}
          ${format ? `<span class="program-activity-tag">${format}</span>` : ""}
        </div>
        <h3>${title || localise(activity.id)}</h3>
        ${localise(activity.description).trim() ? `<p class="program-activity-description">${localise(activity.description).trim()}</p>` : ""}
        <dl class="program-activity-details">${details}</dl>
      </div>
    </article>`;
}

function renderActivities(day = "all") {
  const section = document.getElementById("program-activities");
  const grid = document.getElementById("program-activity-grid");
  const filters = document.getElementById("program-activity-filters");
  if (!section || !grid || !filters) return;

  const activities = programmeActivities2026[eventKey] || [];
  if (!activities.length) {
    section.hidden = true;
    return;
  }

  const currentDay = normaliseDayFilter(day);
  const visibleActivities = activities.filter((activity) => activityHasDay(activity, currentDay));
  section.hidden = false;
  document.querySelector(".program-placeholder")?.setAttribute("hidden", "");
  document.getElementById("program-permalink-note")?.setAttribute("hidden", "");
  setText("program-activities-kicker", copy.activitiesKicker);
  setText("program-activities-title", copy.activitiesTitle);
  setText("program-activities-copy", copy.activitiesCopy);

  const filterOptions = [
    ["all", copy.allActivities],
    ["25", copy.day25],
    ["26", copy.day26]
  ].filter(([value]) => value === "all" || activities.some((activity) => activityHasDay(activity, value)));

  filters.innerHTML = filterOptions
    .map(([value, label]) => `<button class="program-filter-button" type="button" data-day-filter="${value}" aria-pressed="${value === currentDay}">${label}</button>`)
    .join("");

  grid.innerHTML = visibleActivities.map(renderActivityCard).join("");

  filters.querySelectorAll("[data-day-filter]").forEach((button) => {
    button.addEventListener("click", () => renderActivities(button.dataset.dayFilter));
  });
}

